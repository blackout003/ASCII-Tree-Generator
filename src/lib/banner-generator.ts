const FONTS: Record<FontName, Font> = {
  standard: STANDARD,
  small: SMALL,
  slant: SLANT,
  block: BLOCK,
  shadow: SHADOW,
  big: BIG,
  lean: LEAN,
  digital: DIGITAL,
  doom: DOOM,
  mini: MINI,
};

export function generateBanner(text: string, options: BannerOptions): string {
  const font = FONTS[options.font];
  const upper = text.toUpperCase();

  const charData: string[][] = Array.from(upper).map(ch => {
    const lines = font.chars[ch] ?? font.chars[' '] ?? Array(font.height).fill('');
    const w = Math.max(...lines.map(l => l.length));
    return lines.map(l => l.padEnd(w));
  });

  const sep = ' '.repeat(Math.max(0, options.spacing));

  const rows: string[] = [];
  for (let i = 0; i < font.height; i++) {
    rows.push(charData.map(c => c[i] ?? '').join(sep).trimEnd());
  }

  const maxW = Math.max(...rows.map(r => r.length));
  return rows.map(row => {
    if (options.align === 'center') return ' '.repeat(Math.max(0, Math.floor((maxW - row.length) / 2))) + row;
    if (options.align === 'right') return ' '.repeat(Math.max(0, maxW - row.length)) + row;
    return row;
  }).join('\n');
}
